-- SmartFood Delivery : schema initial
-- Montants en francs CFA (entiers). Dates en TIMESTAMPTZ.

-- ============ UTILISATEURS ============
CREATE TABLE roles (
    name VARCHAR(20) PRIMARY KEY
);
INSERT INTO roles(name) VALUES ('CUSTOMER'), ('RESTAURANT'), ('COURIER'), ('ADMIN'), ('SUPERADMIN');

CREATE TABLE users (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email              VARCHAR(160) NOT NULL,
    phone              VARCHAR(30)  NOT NULL,
    password_hash      VARCHAR(100) NOT NULL,
    full_name          VARCHAR(120) NOT NULL,
    status             VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'SUSPENDED')),
    failed_login_count INTEGER      NOT NULL DEFAULT 0,
    locked_until       TIMESTAMPTZ,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_users_email ON users (lower(email));
CREATE UNIQUE INDEX ux_users_phone ON users (phone);

CREATE TABLE user_roles (
    user_id   BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role_name VARCHAR(20) NOT NULL REFERENCES roles (name),
    PRIMARY KEY (user_id, role_name)
);

CREATE TABLE addresses (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT           NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    label      VARCHAR(60)      NOT NULL,
    line       VARCHAR(255)     NOT NULL,
    city       VARCHAR(80)      NOT NULL,
    latitude   DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude  DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    is_default BOOLEAN          NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ      NOT NULL DEFAULT now()
);
CREATE INDEX ix_addresses_user ON addresses (user_id);

CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_refresh_tokens_user ON refresh_tokens (user_id);

CREATE TABLE courier_profiles (
    user_id   BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    available BOOLEAN     NOT NULL DEFAULT FALSE,
    vehicle   VARCHAR(80) NOT NULL DEFAULT 'Moto'
);

-- ============ RESTAURANTS ============
CREATE TABLE restaurants (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id     BIGINT           NOT NULL UNIQUE REFERENCES users (id),
    name         VARCHAR(120)     NOT NULL,
    description  VARCHAR(1000)    NOT NULL DEFAULT '',
    cuisine      VARCHAR(60)      NOT NULL DEFAULT '',
    logo_key     VARCHAR(200),
    address_line VARCHAR(255)     NOT NULL,
    city         VARCHAR(80)      NOT NULL,
    latitude     DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude    DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    phone        VARCHAR(30)      NOT NULL,
    status       VARCHAR(20)      NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'SUSPENDED')),
    accepting    BOOLEAN          NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ      NOT NULL DEFAULT now()
);
CREATE INDEX ix_restaurants_status ON restaurants (status);

CREATE TABLE restaurant_hours (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT  NOT NULL REFERENCES restaurants (id) ON DELETE CASCADE,
    day_of_week   INTEGER NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    opens_at      TIME    NOT NULL,
    closes_at     TIME    NOT NULL,
    UNIQUE (restaurant_id, day_of_week)
);

CREATE TABLE categories (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT      NOT NULL REFERENCES restaurants (id) ON DELETE CASCADE,
    name          VARCHAR(80) NOT NULL,
    position      INTEGER     NOT NULL DEFAULT 0,
    UNIQUE (restaurant_id, name)
);

CREATE TABLE dishes (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT       NOT NULL REFERENCES restaurants (id) ON DELETE CASCADE,
    category_id   BIGINT       REFERENCES categories (id) ON DELETE SET NULL,
    name          VARCHAR(120) NOT NULL,
    description   VARCHAR(600) NOT NULL DEFAULT '',
    price         INTEGER      NOT NULL CHECK (price > 0),
    size_class    VARCHAR(10)  NOT NULL DEFAULT 'MEDIUM' CHECK (size_class IN ('SMALL', 'MEDIUM', 'LARGE')),
    available     BOOLEAN      NOT NULL DEFAULT TRUE,
    archived      BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_dishes_restaurant ON dishes (restaurant_id);

CREATE TABLE dish_images (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dish_id     BIGINT       NOT NULL REFERENCES dishes (id) ON DELETE CASCADE,
    storage_key VARCHAR(200) NOT NULL,
    position    INTEGER      NOT NULL DEFAULT 0
);
CREATE INDEX ix_dish_images_dish ON dish_images (dish_id);

-- ============ COFFRES ============
CREATE TABLE delivery_boxes (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serial              VARCHAR(40) NOT NULL UNIQUE,
    name                VARCHAR(80) NOT NULL,
    courier_id          BIGINT      REFERENCES users (id),
    status              VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'OUT_OF_SERVICE')),
    failed_attempts     INTEGER     NOT NULL DEFAULT 0,
    keypad_locked_until TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- Un livreur ne transporte qu'un coffre a la fois.
CREATE UNIQUE INDEX ux_boxes_courier ON delivery_boxes (courier_id) WHERE courier_id IS NOT NULL;

CREATE TABLE iot_devices (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    box_id            BIGINT           NOT NULL UNIQUE REFERENCES delivery_boxes (id) ON DELETE CASCADE,
    device_uid        VARCHAR(60)      NOT NULL UNIQUE,
    secret_hash       VARCHAR(100)     NOT NULL,
    kind              VARCHAR(20)      NOT NULL CHECK (kind IN ('SIMULATED', 'ESP32')),
    firmware          VARCHAR(40)      NOT NULL DEFAULT 'sim-1.0',
    online            BOOLEAN          NOT NULL DEFAULT TRUE,
    battery_pct       INTEGER          NOT NULL DEFAULT 100 CHECK (battery_pct BETWEEN 0 AND 100),
    temperature_c     DOUBLE PRECISION NOT NULL DEFAULT 25,
    display_text      VARCHAR(80)      NOT NULL DEFAULT '',
    drop_next_command BOOLEAN          NOT NULL DEFAULT FALSE,
    last_seen_at      TIMESTAMPTZ
);

CREATE TABLE compartments (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    box_id    BIGINT      NOT NULL REFERENCES delivery_boxes (id) ON DELETE CASCADE,
    number    INTEGER     NOT NULL CHECK (number > 0),
    size      VARCHAR(10) NOT NULL CHECK (size IN ('SMALL', 'MEDIUM', 'LARGE')),
    size_rank INTEGER     NOT NULL CHECK (size_rank BETWEEN 1 AND 3),
    state     VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE'
        CHECK (state IN ('AVAILABLE', 'RESERVED', 'LOADING', 'OCCUPIED', 'LOCKED', 'WITHDRAWING', 'OPEN', 'FAULT')),
    door_open BOOLEAN     NOT NULL DEFAULT FALSE,
    locked    BOOLEAN     NOT NULL DEFAULT TRUE,
    fault_reason VARCHAR(200),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (box_id, number),
    CHECK ((size = 'SMALL' AND size_rank = 1) OR (size = 'MEDIUM' AND size_rank = 2) OR (size = 'LARGE' AND size_rank = 3))
);
CREATE INDEX ix_compartments_available ON compartments (box_id, size_rank, number) WHERE state = 'AVAILABLE';

-- Etat physique simule (remplace par le vrai materiel en version 2).
CREATE TABLE sim_compartment_hw (
    compartment_id BIGINT PRIMARY KEY REFERENCES compartments (id) ON DELETE CASCADE,
    door_open      BOOLEAN     NOT NULL DEFAULT FALSE,
    latch_engaged  BOOLEAN     NOT NULL DEFAULT TRUE,
    meal_present   BOOLEAN     NOT NULL DEFAULT FALSE,
    fault          VARCHAR(20) NOT NULL DEFAULT 'NONE'
        CHECK (fault IN ('NONE', 'DOOR_AJAR', 'LOCK_STUCK', 'LOCK_BROKEN', 'SENSOR_BROKEN'))
);

-- ============ COMMANDES ============
CREATE TABLE order_groups (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id      BIGINT           NOT NULL REFERENCES users (id),
    address_id       BIGINT           REFERENCES addresses (id) ON DELETE SET NULL,
    delivery_address VARCHAR(400)     NOT NULL,
    delivery_lat     DOUBLE PRECISION NOT NULL,
    delivery_lng     DOUBLE PRECISION NOT NULL,
    subtotal         INTEGER          NOT NULL CHECK (subtotal >= 0),
    delivery_fee     INTEGER          NOT NULL CHECK (delivery_fee >= 0),
    total            INTEGER          NOT NULL CHECK (total >= 0),
    idempotency_key  VARCHAR(64),
    created_at       TIMESTAMPTZ      NOT NULL DEFAULT now(),
    CHECK (total = subtotal + delivery_fee)
);
CREATE INDEX ix_order_groups_customer ON order_groups (customer_id, created_at DESC);
-- Protection contre les commandes repetees (double clic, re-envoi reseau).
CREATE UNIQUE INDEX ux_order_groups_idem ON order_groups (customer_id, idempotency_key) WHERE idempotency_key IS NOT NULL;

CREATE TABLE deliveries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id        BIGINT           NOT NULL REFERENCES order_groups (id),
    box_id          BIGINT           NOT NULL REFERENCES delivery_boxes (id),
    courier_id      BIGINT           NOT NULL REFERENCES users (id),
    status          VARCHAR(20)      NOT NULL DEFAULT 'OFFERED'
        CHECK (status IN ('OFFERED', 'ACCEPTED', 'PICKED_UP', 'IN_TRANSIT', 'ARRIVED', 'COMPLETED', 'CANCELLED')),
    dest_lat        DOUBLE PRECISION NOT NULL,
    dest_lng        DOUBLE PRECISION NOT NULL,
    courier_earning INTEGER          NOT NULL DEFAULT 0 CHECK (courier_earning >= 0),
    created_at      TIMESTAMPTZ      NOT NULL DEFAULT now(),
    picked_up_at    TIMESTAMPTZ,
    arrived_at      TIMESTAMPTZ,
    completed_at    TIMESTAMPTZ
);
CREATE INDEX ix_deliveries_courier ON deliveries (courier_id, status);
CREATE INDEX ix_deliveries_group ON deliveries (group_id);

CREATE TABLE orders (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id      BIGINT      NOT NULL REFERENCES order_groups (id) ON DELETE CASCADE,
    restaurant_id BIGINT      NOT NULL REFERENCES restaurants (id),
    customer_id   BIGINT      NOT NULL REFERENCES users (id),
    delivery_id   BIGINT      REFERENCES deliveries (id),
    status        VARCHAR(20) NOT NULL
        CHECK (status IN ('AWAITING_PAYMENT', 'PENDING', 'ACCEPTED', 'READY', 'RESERVED', 'LOADED',
                          'IN_TRANSIT', 'ARRIVED', 'COLLECTED', 'REJECTED', 'CANCELLED')),
    subtotal      INTEGER     NOT NULL CHECK (subtotal > 0),
    commission    INTEGER     NOT NULL CHECK (commission >= 0),
    required_size VARCHAR(10) NOT NULL CHECK (required_size IN ('SMALL', 'MEDIUM', 'LARGE')),
    reject_reason VARCHAR(300),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_orders_restaurant ON orders (restaurant_id, status);
CREATE INDEX ix_orders_group ON orders (group_id);
CREATE INDEX ix_orders_delivery ON orders (delivery_id);

CREATE TABLE order_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT       NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    dish_id    BIGINT       NOT NULL REFERENCES dishes (id),
    dish_name  VARCHAR(120) NOT NULL,
    unit_price INTEGER      NOT NULL CHECK (unit_price > 0),
    quantity   INTEGER      NOT NULL CHECK (quantity BETWEEN 1 AND 50)
);
CREATE INDEX ix_order_items_order ON order_items (order_id);

CREATE TABLE order_status_history (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT      NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    status     VARCHAR(20) NOT NULL,
    actor_id   BIGINT,
    note       VARCHAR(300),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_order_history_order ON order_status_history (order_id, created_at);

-- ============ PAIEMENTS ============
CREATE TABLE payments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id     BIGINT      NOT NULL UNIQUE REFERENCES order_groups (id) ON DELETE CASCADE,
    method       VARCHAR(20) NOT NULL CHECK (method IN ('CASH_ON_DELIVERY', 'MIXX', 'FLOOZ', 'CARD')),
    status       VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED', 'REFUNDED')),
    amount       INTEGER     NOT NULL CHECK (amount > 0),
    provider     VARCHAR(40) NOT NULL,
    provider_ref VARCHAR(120),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE payment_transactions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id   BIGINT      NOT NULL REFERENCES payments (id) ON DELETE CASCADE,
    type         VARCHAR(20) NOT NULL CHECK (type IN ('CHARGE', 'REFUND')),
    status       VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED')),
    amount       INTEGER     NOT NULL CHECK (amount > 0),
    provider_ref VARCHAR(120),
    detail       VARCHAR(300),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_payment_tx_payment ON payment_transactions (payment_id);

CREATE TABLE payment_webhooks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider     VARCHAR(40)  NOT NULL,
    event_id     VARCHAR(120) NOT NULL,
    payload      TEXT         NOT NULL,
    received_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    processed_at TIMESTAMPTZ,
    UNIQUE (provider, event_id)
);

-- ============ LIVRAISONS ============
CREATE TABLE delivery_assignments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id  BIGINT      NOT NULL REFERENCES deliveries (id) ON DELETE CASCADE,
    courier_id   BIGINT      NOT NULL REFERENCES users (id),
    status       VARCHAR(20) NOT NULL DEFAULT 'OFFERED' CHECK (status IN ('OFFERED', 'ACCEPTED', 'REJECTED')),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    responded_at TIMESTAMPTZ
);
CREATE INDEX ix_delivery_assignments_delivery ON delivery_assignments (delivery_id);

CREATE TABLE delivery_locations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id BIGINT           NOT NULL REFERENCES deliveries (id) ON DELETE CASCADE,
    courier_id  BIGINT           NOT NULL REFERENCES users (id),
    latitude    DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude   DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    accuracy_m  DOUBLE PRECISION,
    simulated   BOOLEAN          NOT NULL DEFAULT FALSE,
    recorded_at TIMESTAMPTZ      NOT NULL DEFAULT now()
);
CREATE INDEX ix_delivery_locations ON delivery_locations (delivery_id, recorded_at DESC);

-- ============ AFFECTATIONS, AUTORISATIONS, CODES ============
CREATE TABLE compartment_assignments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compartment_id BIGINT      NOT NULL REFERENCES compartments (id),
    order_id       BIGINT      NOT NULL REFERENCES orders (id),
    active         BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    released_at    TIMESTAMPTZ
);
-- Un compartiment ne peut pas accueillir deux commandes actives.
CREATE UNIQUE INDEX ux_assignment_active_compartment ON compartment_assignments (compartment_id) WHERE active;
-- Une commande n'occupe qu'un compartiment a la fois.
CREATE UNIQUE INDEX ux_assignment_active_order ON compartment_assignments (order_id) WHERE active;

CREATE TABLE opening_authorizations (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compartment_id BIGINT      NOT NULL REFERENCES compartments (id),
    order_id       BIGINT      NOT NULL REFERENCES orders (id),
    user_id        BIGINT      NOT NULL REFERENCES users (id),
    purpose        VARCHAR(20) NOT NULL CHECK (purpose IN ('LOADING', 'WITHDRAWAL')),
    expires_at     TIMESTAMPTZ NOT NULL,
    used_at        TIMESTAMPTZ,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_opening_auth_compartment ON opening_authorizations (compartment_id, created_at DESC);

CREATE TABLE withdrawal_codes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       BIGINT       NOT NULL REFERENCES orders (id),
    customer_id    BIGINT       NOT NULL REFERENCES users (id),
    box_id         BIGINT       NOT NULL REFERENCES delivery_boxes (id),
    compartment_id BIGINT       NOT NULL REFERENCES compartments (id),
    code_hash      VARCHAR(64)  NOT NULL,
    code_encrypted VARCHAR(200) NOT NULL,
    status         VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'USED', 'EXPIRED', 'REVOKED')),
    expires_at     TIMESTAMPTZ  NOT NULL,
    used_at        TIMESTAMPTZ,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CHECK ((status = 'USED') = (used_at IS NOT NULL))
);
-- Un seul code actif par commande ; deux codes actifs identiques sont impossibles sur un meme coffre.
CREATE UNIQUE INDEX ux_code_active_order ON withdrawal_codes (order_id) WHERE status = 'ACTIVE';
CREATE UNIQUE INDEX ux_code_active_box_hash ON withdrawal_codes (box_id, code_hash) WHERE status = 'ACTIVE';

CREATE TABLE opening_events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    box_id         BIGINT      NOT NULL REFERENCES delivery_boxes (id) ON DELETE CASCADE,
    compartment_id BIGINT      REFERENCES compartments (id) ON DELETE CASCADE,
    order_id       BIGINT,
    actor_id       BIGINT,
    type           VARCHAR(40) NOT NULL,
    success        BOOLEAN     NOT NULL,
    detail         VARCHAR(300),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_opening_events_box ON opening_events (box_id, created_at DESC);

CREATE TABLE sensor_events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id      BIGINT      NOT NULL REFERENCES iot_devices (id) ON DELETE CASCADE,
    compartment_no INTEGER,
    type           VARCHAR(40) NOT NULL,
    value          VARCHAR(120),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_sensor_events_device ON sensor_events (device_id, created_at DESC);

CREATE TABLE device_heartbeats (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id     BIGINT           NOT NULL REFERENCES iot_devices (id) ON DELETE CASCADE,
    battery_pct   INTEGER          NOT NULL,
    temperature_c DOUBLE PRECISION NOT NULL,
    created_at    TIMESTAMPTZ      NOT NULL DEFAULT now()
);
CREATE INDEX ix_heartbeats_device ON device_heartbeats (device_id, created_at DESC);

-- ============ NOTIFICATIONS, RECLAMATIONS ============
CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type       VARCHAR(40)  NOT NULL,
    title      VARCHAR(160) NOT NULL,
    body       VARCHAR(600) NOT NULL,
    link       VARCHAR(200),
    read_at    TIMESTAMPTZ,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_notifications_user ON notifications (user_id, created_at DESC);

CREATE TABLE notification_preferences (
    user_id BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    in_app  BOOLEAN NOT NULL DEFAULT TRUE,
    email   BOOLEAN NOT NULL DEFAULT FALSE,
    sms     BOOLEAN NOT NULL DEFAULT FALSE,
    push    BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE complaints (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT        NOT NULL REFERENCES users (id),
    order_id   BIGINT        REFERENCES orders (id),
    subject    VARCHAR(160)  NOT NULL,
    message    VARCHAR(2000) NOT NULL,
    status     VARCHAR(20)   NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED')),
    response   VARCHAR(2000),
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX ix_complaints_status ON complaints (status, created_at DESC);

-- ============ SECURITE ============
-- Pas de cles etrangeres : les journaux doivent survivre aux suppressions.
CREATE TABLE audit_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    BIGINT,
    action      VARCHAR(60) NOT NULL,
    entity_type VARCHAR(40),
    entity_id   BIGINT,
    detail      VARCHAR(600),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_audit_created ON audit_logs (created_at DESC);

CREATE TABLE security_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type       VARCHAR(40) NOT NULL,
    user_id    BIGINT,
    box_id     BIGINT,
    detail     VARCHAR(600),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_security_created ON security_events (created_at DESC);
